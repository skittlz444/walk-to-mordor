#!/usr/bin/env node
'use strict';

/**
 * Generate the deterministic asset version maps:
 *
 *   src/generated/asset-versions.ts   server entry assets (CSS, icons, JS, manifest)
 *   public/img/image-versions.json    runtime image assets (excludes map tiles)
 *
 * Usage:
 *   node scripts/generate-asset-versions.js
 *   node scripts/generate-asset-versions.js --check
 *   node scripts/generate-asset-versions.js --write-tile-version
 *
 * `--check` never writes: it verifies both maps and the committed map-tile-set
 * version, exiting non-zero on drift. `--write-tile-version` is a temporary
 * maintenance helper for the current committed metadata; task 3.4 moves this
 * into `scripts/tile-map-image.js`.
 */

const fs = require('fs');
const path = require('path');

const {
  MissingInputError,
  PUBLIC_DIR,
  ROOT,
  buildEntryAssetMap,
  buildImageAssetMap,
  buildImageVersionsFile,
  computeTileSetVersion,
  formatJson,
  requireJsonFile,
} = require('./lib/asset-manifest');

const ENTRY_MAP_PATH = path.join(ROOT, 'src', 'generated', 'asset-versions.ts');
const IMAGE_MAP_PATH = path.join(PUBLIC_DIR, 'img', 'image-versions.json');
const TILE_METADATA_PATH = path.join(PUBLIC_DIR, 'img', 'map', 'tiles', 'metadata.json');
const TILE_DIR = path.join(PUBLIC_DIR, 'img', 'map', 'tiles');

function renderEntryModule(assets) {
  const entries = Object.keys(assets)
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(assets[key])},`)
    .join('\n');

  return `// AUTO-GENERATED FILE - DO NOT EDIT.
// Generated by scripts/generate-asset-versions.js. Run \`npm run generate:assets\`.
// Entry assets under public/css/**, public/icons/**, public/js/** (client chunks
// excluded), plus /manifest.json. Images live in public/img/image-versions.json.

export const ASSET_VERSIONS: Readonly<Record<string, string>> = {
${entries}
};
`;
}

function readCommittedJson(absPath, label) {
  if (!fs.existsSync(absPath)) {
    return null;
  }
  try {
    return JSON.parse(fs.readFileSync(absPath, 'utf8'));
  } catch (error) {
    throw new MissingInputError(`Committed ${label} is not valid JSON (${absPath}): ${error.message}`);
  }
}

function describeAssetDiff(expectedAssets, actualAssets) {
  const expectedKeys = Object.keys(expectedAssets);
  const actualKeys = Object.keys(actualAssets);
  const actual = new Set(actualKeys);
  const expected = new Set(expectedKeys);
  const problems = [];

  for (const key of expectedKeys) {
    if (!actual.has(key)) {
      problems.push(`missing entry: ${key}`);
    } else if (actualAssets[key] !== expectedAssets[key]) {
      problems.push(`stale version: ${key} (committed ${actualAssets[key]}, expected ${expectedAssets[key]})`);
    }
  }
  for (const key of actualKeys) {
    if (!expected.has(key)) {
      problems.push(`stale entry: ${key} (no longer exists)`);
    }
  }
  return problems;
}

function writeFile(absPath, content) {
  fs.mkdirSync(path.dirname(absPath), { recursive: true });
  fs.writeFileSync(absPath, content);
}

function checkTileVersion(problems) {
  const metadata = requireJsonFile(TILE_METADATA_PATH, 'public/img/map/tiles/metadata.json');
  const expectedVersion = computeTileSetVersion(TILE_DIR);

  if (!metadata.version) {
    problems.push(
      `public/img/map/tiles/metadata.json has no "version" field (expected ${expectedVersion}); ` +
        'rerun the tile generator once task 3.4 lands, or run `npm run generate:assets -- --write-tile-version`'
    );
    return;
  }
  if (metadata.version !== expectedVersion) {
    problems.push(
      `stale tile-set version in public/img/map/tiles/metadata.json ` +
        `(committed ${metadata.version}, expected ${expectedVersion}); tile bytes changed without a metadata update`
    );
  }
}

function writeTileVersion() {
  const metadata = requireJsonFile(TILE_METADATA_PATH, 'public/img/map/tiles/metadata.json');
  const version = computeTileSetVersion(TILE_DIR);
  if (metadata.version === version) {
    console.log(`✓ Tile-set version already current: ${version}`);
    return;
  }
  const updated = { ...metadata, version };
  fs.writeFileSync(TILE_METADATA_PATH, JSON.stringify(updated, null, 2));
  console.log(`✓ Wrote tile-set version ${version} to public/img/map/tiles/metadata.json`);
}

function run({ check, writeTileVersionOnly }) {
  if (writeTileVersionOnly) {
    writeTileVersion();
    return;
  }

  // Compute everything before touching disk so a missing input never leaves a
  // partial or empty artifact behind.
  const entryAssets = buildEntryAssetMap();
  const imageAssets = buildImageAssetMap();
  const entryModule = renderEntryModule(entryAssets);
  const imageMap = buildImageVersionsFile(imageAssets);
  const imageMapJson = formatJson(imageMap);

  const problems = [];

  if (check) {
    const committedEntry = fs.existsSync(ENTRY_MAP_PATH)
      ? fs.readFileSync(ENTRY_MAP_PATH, 'utf8')
      : null;
    if (committedEntry === null) {
      problems.push('missing generated artifact: src/generated/asset-versions.ts');
    } else if (committedEntry !== entryModule) {
      problems.push('stale generated artifact: src/generated/asset-versions.ts');
    }

    const committedImageMap = readCommittedJson(IMAGE_MAP_PATH, 'public/img/image-versions.json');
    if (!committedImageMap) {
      problems.push('missing generated artifact: public/img/image-versions.json');
    } else if (fs.readFileSync(IMAGE_MAP_PATH, 'utf8') !== imageMapJson) {
      problems.push('stale generated artifact: public/img/image-versions.json');
      const committedAssets =
        committedImageMap.assets && typeof committedImageMap.assets === 'object'
          ? committedImageMap.assets
          : {};
      problems.push(
        ...describeAssetDiff(imageAssets, committedAssets).map(
          (problem) => `public/img/image-versions.json: ${problem}`
        )
      );
    }

    checkTileVersion(problems);

    if (problems.length > 0) {
      for (const problem of problems) {
        console.error(`❌ ${problem}`);
      }
      console.error(`\n❌ Asset version check failed (${problems.length} problem(s)). Run \`npm run generate:assets\`.`);
      process.exitCode = 1;
      return;
    }

    console.log(
      `✓ Asset versions are current (${Object.keys(entryAssets).length} entry assets, ` +
        `${Object.keys(imageAssets).length} images, tile version ${computeTileSetVersion(TILE_DIR)}).`
    );
    return;
  }

  writeFile(ENTRY_MAP_PATH, entryModule);
  writeFile(IMAGE_MAP_PATH, imageMapJson);
  console.log(`✓ Wrote src/generated/asset-versions.ts (${Object.keys(entryAssets).length} entries)`);
  console.log(
    `✓ Wrote public/img/image-versions.json (${Object.keys(imageAssets).length} images, version ${imageMap.version})`
  );

  if (!fs.existsSync(TILE_METADATA_PATH)) {
    throw new MissingInputError('Missing required input file: public/img/map/tiles/metadata.json');
  }
  const metadata = requireJsonFile(TILE_METADATA_PATH, 'public/img/map/tiles/metadata.json');
  const tileVersion = computeTileSetVersion(TILE_DIR);
  if (!metadata.version) {
    console.warn(
      `⚠️  public/img/map/tiles/metadata.json has no "version" (expected ${tileVersion}); ` +
        'run `npm run generate:assets -- --write-tile-version` once.'
    );
  } else if (metadata.version !== tileVersion) {
    console.warn(
      `⚠️  public/img/map/tiles/metadata.json version is stale ` +
        `(committed ${metadata.version}, expected ${tileVersion}).`
    );
  }
}

function main() {
  const args = process.argv.slice(2);
  try {
    run({ check: args.includes('--check'), writeTileVersionOnly: args.includes('--write-tile-version') });
  } catch (error) {
    console.error(`❌ ${error.message}`);
    process.exitCode = 1;
  }
}

if (require.main === module) {
  main();
}
