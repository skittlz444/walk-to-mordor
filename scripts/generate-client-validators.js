#!/usr/bin/env node

/**
 * Generates public/js/validators.js from src/validators-client.ts.
 *
 * The legacy scripts load a classic (non-module) script that exposes
 * `window.validators`. This bundles the shared TypeScript validators into that
 * script so the client and the Worker can never drift.
 *
 * Usage:
 *   node scripts/generate-client-validators.js          # write the file
 *   node scripts/generate-client-validators.js --check  # fail if out of date
 */

const fs = require('fs');
const path = require('path');
const { buildSync } = require('esbuild');

const root = path.resolve(__dirname, '..');
const outfile = path.join(root, 'public', 'js', 'validators.js');
const header =
  '// @generated by scripts/generate-client-validators.js — edit src/validators*.ts instead.\n';

const result = buildSync({
  entryPoints: [path.join(root, 'src', 'validators-client.ts')],
  bundle: true,
  format: 'iife',
  target: ['es2020'],
  write: false,
  legalComments: 'none',
  logLevel: 'silent',
});

const output = header + result.outputFiles[0].text;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outfile) ? fs.readFileSync(outfile, 'utf8') : '';
  if (current !== output) {
    console.error(
      'public/js/validators.js is out of date. Run `npm run build:validators`.',
    );
    process.exit(1);
  }
  console.log('public/js/validators.js is up to date.');
} else {
  fs.writeFileSync(outfile, output);
  console.log('wrote public/js/validators.js');
}
